"""The AgentDojo harness runs the real banking suite through the engine.

Scripted mode is deterministic: no API key, no network. It executes each task's
ground-truth calls, so it measures the enforcement layer at its worst case (an agent that
always follows the injected instruction), not a model's susceptibility.
"""

from __future__ import annotations

from typing import Any

import pytest

pytest.importorskip("agentdojo")

from agentdojo.task_suite.load_suites import get_suite  # noqa: E402

from agentshield.bench import (  # noqa: E402
    BenchReport,
    banking_policy,
    format_markdown,
    format_table,
    run_benchmark,
)
from agentshield.cli import main  # noqa: E402

USER_TASKS = ["user_task_1", "user_task_3"]
INJECTION_TASKS = ["injection_task_0", "injection_task_7"]


@pytest.fixture(scope="module")
def report() -> BenchReport:
    return run_benchmark(user_tasks=USER_TASKS, injection_tasks=INJECTION_TASKS)


def test_policy_declares_every_banking_tool() -> None:
    suite = get_suite("v1.2.2", "banking")
    assert {function.name for function in suite.tools} == set(banking_policy().tools)


def test_unshielded_baseline(report: BenchReport) -> None:
    metrics = report.config("unshielded").metrics
    assert metrics.utility == 1.0
    assert metrics.utility_under_attack == 1.0
    assert metrics.attack_success_rate == 1.0
    assert metrics.blocked == 0


def test_shield_blocks_the_injected_sink(report: BenchReport) -> None:
    metrics = report.config("shielded").metrics
    assert metrics.attack_success_rate == 0.0
    assert metrics.blocked > 0
    assert metrics.approval_requests > 0


def test_shield_keeps_a_read_only_task(report: BenchReport) -> None:
    shielded = report.config("shielded")
    result = next(
        task
        for task in shielded.tasks
        if task.user_task == "user_task_1" and task.injection_task is None
    )
    assert result.utility is True
    assert [call.tool for call in result.calls] == ["get_most_recent_transactions"]


def test_ask_is_denied_without_a_human(report: BenchReport) -> None:
    shielded = report.config("shielded")
    result = next(
        task
        for task in shielded.tasks
        if task.user_task == "user_task_3" and task.injection_task is None
    )
    blocked = [call for call in result.calls if not call.executed]
    assert blocked and blocked[0].verdict == "ask"
    assert result.utility is False  # the legitimate send was blocked too


def test_report_shapes(report: BenchReport) -> None:
    payload = report.as_dict()
    metadata = payload["metadata"]
    assert metadata["suite"] == "banking"
    assert metadata["mode"] == "scripted"
    assert metadata["attack"] is None
    assert {"agentdojo", "commit", "date"} <= set(metadata)
    metrics: dict[str, Any] = payload["configs"][0]["metrics"]
    assert metrics["config"] == "unshielded"
    assert "attack_success_rate" in metrics
    assert "utility_under_attack" in metrics


def test_formatters(report: BenchReport) -> None:
    table = format_table(report)
    assert "utility-under-attack" in table
    assert "attack-success-rate" in table
    assert "shielded" in table
    markdown = format_markdown(report)
    assert markdown.startswith("<!-- generated by agentshield bench")
    assert "| shielded |" in markdown


def test_cli_bench(capsys: pytest.CaptureFixture[str]) -> None:
    code = main(
        [
            "bench",
            "--user-tasks",
            "user_task_1",
            "--injection-tasks",
            "injection_task_0",
        ]
    )
    assert code == 0
    out = capsys.readouterr().out
    assert "attack-success-rate" in out
    assert "unshielded" in out
    assert "shielded" in out
